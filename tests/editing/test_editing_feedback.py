def test_every_rating_has_a_polarity_and_a_reason_category():
    """The two lookups every consumer depends on must cover the vocabulary.

    A rating missing from either table would silently become "neutral" and
    "preference", which is a wrong label rather than a missing one.
    """
    for rating in RATINGS:
        assert rating in POLARITY_FOR_RATING, rating
        assert rating in DEFAULT_REASON_FOR_RATING, rating
        assert DEFAULT_REASON_FOR_RATING[rating] in REASON_CATEGORIES


def test_the_prompt_vocabulary_is_covered():
    assert len(set(RATINGS)) == len(RATINGS), "a rating is listed twice"
    for expected in ("good", "bad", "okay", "unsure", "keep", "cut",
                     "shorten", "extend", "move_earlier", "move_later",
                     "too_much", "too_little", "wrong_moment", "wrong_style",
                     "funny", "boring", "confusing", "hype", "useful_context",
                     "useless_context", "bad_caption", "good_caption",
                     "bad_music_sfx", "good_music_sfx", "bad_hook",
                     "good_hook", "bad_pacing", "strong_payoff",
                     "weak_payoff", "good_callback", "forced_callback",
                     "strong_retention", "weak_retention"):
        assert expected in RATINGS, expected
    for category in ("pacing", "story", "clarity", "retention", "comedy",
                     "emotion", "visual", "audio", "caption", "timing",
                     "style", "safety", "technical", "preference"):
        assert category in REASON_CATEGORIES, category


def test_every_target_type_maps_to_a_training_task():
    for target_type in TARGET_TYPES:
        assert target_type in TASK_FOR_TARGET, target_type
        assert TASK_FOR_TARGET[target_type] in TASK_TYPES


def test_a_feedback_item_round_trips_through_json(session):
    item = FeedbackItem(
        session_id=session.session_id,
        target=FeedbackTarget(target_type="layer_item", target_id="li_danger",
                              start=12.0, end=15.0, label="a caption",
                              resolved=True, checked=True),
        rating=FeedbackRating(rating="too_much", strength=0.8),
        note="one too many",
        correction=build_correction("cut this shorter", seconds=1.5),
        confidence=0.9,
    ).settle()

    restored = FeedbackItem.from_dict(
        json.loads(json.dumps(item.to_dict()))
    )
    assert restored.feedback_id == item.feedback_id
    assert restored.rating.rating == "too_much"
    assert restored.polarity == "corrective"
    assert restored.correction is not None
    assert restored.correction.action == "shorten"
    assert restored.correction.seconds == 1.5
    assert restored.target.target_id == "li_danger"


def test_an_unknown_rating_is_refused_rather_than_coerced(
    config, session, artifacts
):
    """A typo must not enter the data as a real opinion.

    The whole vocabulary exists so ratings can be counted; coercing 'meh' to
    'okay' would put a neutral judgement in the log that nobody gave.
    """
    with pytest.raises(EditingError) as error:
        rate(config, session, artifacts, "li_danger", "meh")
    assert "not a rating" in str(error.value)
    assert "good" in error.value.hint


def test_reason_words_from_the_rating_vocabulary_are_kept_not_dropped():
    """``--reason boring`` is what people type, and it means something."""
    reasons = reasons_from(["boring"])
    assert [r.category for r in reasons] == ["pacing"]
    assert "boring" in reasons[0].detail

    # An unknown word is filed rather than discarded.
    unknown = reasons_from(["the music swells oddly"])
    assert unknown[0].category == "preference"
    assert "music swells" in unknown[0].detail


def test_a_correction_action_is_read_longest_phrase_first():
    """"cut this shorter" is a shorten, not a cut.

    Same rule as Session 8's cue families: a short phrase inside a longer one
    must not be able to claim it.
    """
    assert action_from_text("cut this shorter") == "shorten"
    assert action_from_text("cut this") == "cut"
    assert action_from_text("move it later") == "move_later"
    assert action_from_text("") == "none"


def test_a_directional_correction_with_no_number_is_not_specific():
    vague = build_correction("make it shorter")
    assert vague is not None and vague.action == "shorten"
    assert not vague.is_specific, "no idea how much shorter"

    exact = build_correction("make it shorter", seconds=-2.0)
    assert exact is not None and exact.is_specific

    # A non-measurable correction is specific enough as text alone.
    swap = build_correction("different music please")
    assert swap is not None and swap.is_specific


