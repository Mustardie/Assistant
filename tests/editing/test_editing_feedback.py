def test_near_identical_prompts_at_one_moment_collapse():
    """Three captions in five seconds is one thing to look at, not three."""
    def caption(index: int, start: float) -> ReviewPrompt:
        return ReviewPrompt(
            prompt_id=f"q_{index}", source="style", category="caption",
            priority=0.4 + index * 0.01,
            target=FeedbackTarget(target_type="layer_item",
                                  target_id=f"li_{index}",
                                  start=start, end=start + 1.0),
        )

    folded = queue_module.collapse_nearby(
        [caption(0, 10.0), caption(1, 11.0), caption(2, 13.0),
         caption(3, 60.0)]
    )
    assert len(folded) == 2, [p.prompt_id for p in folded]
    kept = max(folded, key=lambda p: p.duplicates)
    assert kept.duplicates == 2

    # A different kind of thing at the same moment is a busy moment, not a
    # duplicate, and is left alone.
    asset = ReviewPrompt(
        prompt_id="q_a", source="assets", category="audio", priority=0.5,
        target=FeedbackTarget(target_type="asset_placement",
                              target_id="ap_1", start=10.5, end=11.0),
    )
    mixed = queue_module.collapse_nearby([caption(0, 10.0), asset])
    assert len(mixed) == 2


