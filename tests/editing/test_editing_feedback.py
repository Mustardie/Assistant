def test_the_feedback_package_reaches_for_nothing_external():
    """Guards the promise in the module docstring, in one place.

    Every input to this layer is JSON another pass already wrote. If a module
    here ever imports the model client, FFmpeg or the Premiere bridge, the
    review stops working on a machine that has none of them -- which is most
    of the machines this will run on.
    """
    import importlib
    import inspect

    forbidden = ("editing.ffmpeg", "editing.visual.qwen",
                 "editing.premiere_link", "premiere")
    for name in ("schema", "store", "targets", "queue", "collect",
                 "signals", "training", "export", "report"):
        module = importlib.import_module(f"editing.feedback.{name}")
        source = inspect.getsource(module)
        for banned in forbidden:
            assert f"import {banned}" not in source, (name, banned)
            assert f"from {banned}" not in source, (name, banned)
