def test_appending_never_rewrites_an_earlier_line(config, session, artifacts):
    """The load-bearing guarantee of the whole layer, asserted on bytes."""
    rate(config, session, artifacts, "li_danger", "good")
    path = store_module.log_path(config, session.session_id)
    after_one = path.read_bytes()

    rate(config, session, artifacts, "li_punch", "bad")
    rate(config, session, artifacts, "p_0", "keep")
    after_three = path.read_bytes()

    assert after_three.startswith(after_one), (
        "an earlier line was rewritten; the log must only ever grow")
    assert len(after_three.splitlines()) == 3


def test_re_rating_supersedes_without_deleting(config, session, artifacts):
    first = rate(config, session, artifacts, "li_danger", "bad",
                 note="too much")
    second = rate(config, session, artifacts, "li_danger", "good_caption",
                  note="changed my mind")

    history = store_module.read_all(config, session.session_id)
    current = store_module.read_current(config, session.session_id)

    assert len(history) == 2, "the original opinion is still in the file"
    assert len(current) == 1, "only the later one stands"
    assert current[0].feedback_id == second.feedback_id
    assert second.supersedes == first.feedback_id
    assert [item.rating.rating for item in
            store_module.history_of(history, first.target.key())] == [
        "bad", "good_caption"]


def test_changing_your_mind_does_not_move_the_item_down_the_list(
    config, session, artifacts
):
    """A reviewer reading top to bottom should not have items jump around.

    ``read_current`` is a view over the log, so the naive implementation orders
    by last write -- re-rating the first item sends it to the bottom, which is
    the opposite of what someone working through a list wants.
    """
    rate(config, session, artifacts, "li_danger", "bad")
    rate(config, session, artifacts, "li_punch", "good")
    rate(config, session, artifacts, "p_0", "keep")
    rate(config, session, artifacts, "li_danger", "good_caption")

    current = store_module.read_current(config, session.session_id)
    assert [item.target.target_id for item in current] == [
        "li_danger", "li_punch", "p_0"]
    assert current[0].rating.rating == "good_caption", "and it is the new one"


