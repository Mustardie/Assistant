def test_the_queue_draws_on_every_pass_that_ran(artifacts):
    queue = queue_module.build(artifacts, limit=60)
    sources = {prompt.source for prompt in queue.prompts}
    assert {"roughcut", "recommend", "critic", "style", "assets", "episode",
            "retention", "edit"} <= sources


def test_the_queue_prioritises_uncertain_and_high_impact_decisions(artifacts):
    queue = queue_module.build(artifacts, limit=10)
    top = queue.prompts[:5]
    interesting = [
        prompt for prompt in top
        if prompt.has_flag("uncertain") or prompt.has_flag("high_impact")
        or prompt.has_flag("structural")
    ]
    assert len(interesting) >= 4, [p.line() for p in top]

    # ...and the flags genuinely raise priority rather than being decoration.
    flagged = [p for p in queue.prompts if p.has_flag("structural")]
    plain = [p for p in queue.prompts
             if not p.flags or p.flags == ["positive_sample"]]
    if flagged and plain:
        assert max(p.priority for p in flagged) > min(
            p.priority for p in plain)


def test_the_queue_includes_retention_risks_and_hook_candidates(artifacts):
    queue = queue_module.build(artifacts, limit=25)
    assert queue.flagged("retention_risk"), "a risk zone must reach the queue"
    assert queue.flagged("structural"), "hooks/peak/ending must reach it"

    questions = " ".join(prompt.question for prompt in queue.prompts)
