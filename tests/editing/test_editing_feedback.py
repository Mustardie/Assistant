"""The feedback collector: what was asked, what was said, and what survives.

Four properties carry the weight, and each is asserted from several angles.

**Nothing is ever lost.** The log is append-only, and that is tested three
ways: appending preserves every earlier line byte for byte, re-rating keeps
both versions, and starting a session over one that holds feedback is refused.
This is the only artifact in the whole system that cannot be regenerated by
re-running a pass, so losing a line of it is unrecoverable in a way nothing
else here is.

**Feedback stays attached to evidence.** A rating resolves to the record it
was about, keeps the artifact path and the source IDs, and an ID that matches
nothing produces an error naming every collection that was searched -- because
the usual cause is a pass that never ran, not a typo.

**Uncertainty survives.** ``unsure`` is a rating, never coerced away, and it is
structurally incapable of becoming training data. A preference built on two
ratings cannot claim the confidence of one built on six, and disagreement is
counted rather than filtered out.

**Nothing is trained, and nothing is claimed.** No pass reads a preference
signal; ``safe_to_apply_automatically`` describes evidence rather than granting
permission; and every report carries ``NOT_MEASURED`` verbatim.

Nothing here needs FFmpeg, a GPU, a model server, Premiere or real footage.
"""
