# Assets
# ---------------------------------------------------------------------------

def _resolve_assets(
    cues: Sequence[AudioCue], library, plan: AudioPolishPlan
) -> None:
    """Match accepted cues against the local library.

    A cue that matches nothing stays a placeholder and is marked missing. That
    is the honest outcome and it is also the useful one: the missing list is a
    shopping list.
    """
    from editing.assets.match import best_match, rank_candidates

    if library is None:
        plan.warnings.append(
            "audio polish was asked to use the asset library and none was "
            "available, so every cue stayed a placeholder."
        )
        for cue in cues:
            if cue.accepted and cue.kind in CUE_REQUIREMENT:
                cue.missing_asset = True
                cue.safety_notes.append("no asset library was readable")
        return

    plan.library_root = str(getattr(library, "root", "") or "")
    plan.library_size = len(getattr(library, "items", ()) or ())
    used: dict = {}

    for cue in cues:
        if not cue.accepted:
            continue
        requirement = CUE_REQUIREMENT.get(cue.kind)
        if requirement is None:
            # A silence drop has no file. Not missing -- there is nothing to
            # find, and putting it on a shopping list would be nonsense.
            cue.safety_notes.append(
                "nothing is placed here: the absence of sound is the cue")
            continue

        matches = rank_candidates(
            requirement, library,
            style=plan.style, slot_duration=cue.duration, used=used,
        )
        match = best_match(matches)
        if match is None:
            cue.missing_asset = True
            cue.placeholder_only = True
            cue.safety_notes.append(
                f"nothing in the library satisfies {requirement}")
            continue

        # ``AssetMatch`` carries the id and the filename; the path lives on the
        # library item, and the cue needs it because a person following this
        # plan has to be able to find the file.
        item = library.by_id(match.asset_id)
        cue.asset_id = match.asset_id
        cue.asset_path = str(getattr(item, "path", "") or "")
        cue.asset_filename = match.filename or str(
            getattr(item, "filename", "") or "")
        cue.match_score = float(getattr(match, "score", 0.0) or 0.0)
        cue.placeholder_only = False
        used[cue.asset_id] = used.get(cue.asset_id, 0) + 1
        cue.safety_notes.append(
            "matched on tags, folder and duration. Nothing has listened to "
            "this file and its level has not been measured")


def _finish(
    plan: AudioPolishPlan, cues: Sequence[AudioCue], config: AudioPolishConfig
) -> None:
    plan.cues = list(cues)
    missing = plan.missing
    if missing:
        plan.warnings.append(
            f"{len(missing)} cue(s) have no asset behind them. They are in "
            "the plan as placeholders and on the shopping list."
        )
    if config.uses_library and not plan.library_size:
        plan.warnings.append(
            "the asset library is empty, so every cue is a placeholder. That "
            "list is a useful thing to go shopping with."
        )
    plan.safety_notes.append(
        "No level in this plan has been measured, and nothing here has been "
        "listened to. Check every cue against the commentary by ear."
    )
    plan.safety_notes.append(
        "Nothing in this plan is in the rendered proxy: the proxy assembles "
        "V1 only and carries no added audio."
    )


def _reject(cue: AudioCue, code: str, detail: str) -> None:
    cue.accepted = False
    cue.reject_reason = code
    cue.reject_detail = detail
