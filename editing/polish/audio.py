def _speech_spans(
    timeline: StructureTimeline, cut: RoughCutPlan
) -> list[tuple]:
    """Every spoken line, mapped onto the cut. Lines cut out are dropped."""
    from editing.roughcut.select import map_to_sequence

    out: list[tuple] = []
    for segment in timeline.segments:
        for entry in segment.speech_entries:
            if not (entry.text or "").strip():
                continue
            start = map_to_sequence(
                cut.placements, segment.asset_id, entry.start)
            if start is None:
                continue
            end = map_to_sequence(cut.placements, segment.asset_id, entry.end)
            out.append((start, end if end is not None else start + 0.5))
    out.sort()
    return out


def _covers_speech(
    cue: AudioCue, speech: Sequence[tuple], guard: float
) -> Optional[float]:
    """Where a cue would land on a word, or None when it would not.

    ``None`` rather than ``0.0`` for "clear", because a line spoken at the
    very start of the cut is at 0.0 and a falsy sentinel would wave it
    through -- which is the one moment an automated edit most obviously
    announces itself.
    """
    low, high = cue.start - guard, cue.end + guard
    for start, end in speech:
        if high > start and low < end:
            return start
    return None


def _apply_budget(
    cues: list[AudioCue], config: AudioPolishConfig, plan: AudioPolishPlan
) -> None:
    """Thin the surviving cues until they fit the ceilings.

    Only cues that have not already been refused take part: a cue rejected for
    covering speech must not consume budget that a good one could have used.
    """
    live = [cue for cue in cues if not cue.reject_reason]
    minutes = max(plan.cut_duration, 1.0) / 60.0
    allowed = int(config.max_sfx_per_minute * minutes)
    if config.max_sfx_per_minute > 0 and allowed < 1:
        # Same floor the caption budget uses, for the same reason: a rate that
        # rounds down to nothing on a short cut would silently disable the
        # feature rather than limit it.
        allowed = 1
        plan.safety_notes.append(
            f"the cut is {plan.cut_duration:.0f}s, so "
            f"{config.max_sfx_per_minute:.2f} effects a minute rounds down to "
            "none. One was allowed, which reads above the ceiling in the "
            "density figure."
        )

    ranked = sorted(live, key=lambda cue: (-cue.priority, cue.start))
    kept: list[AudioCue] = []
    effects = 0

    for cue in ranked:
        clash = _too_close(cue, kept, config.min_spacing)
        if clash is not None:
            _reject(cue, "too_close_to_another",
                    f"{abs(cue.start - clash.start):.1f}s from the "
                    f"{clash.kind} at {clash.start:.1f}s, and this style asks "
                    f"for {config.min_spacing:.0f}s between two cues")
            continue
        if cue.counts_as_sfx:
            if effects >= allowed:
                _reject(cue, "density_limit",
                        f"the effect budget for this cut is {allowed} "
                        f"({config.max_sfx_per_minute:.1f} a minute over "
                        f"{plan.cut_duration:.0f}s), and stronger moments "
                        "filled it")
                continue
            if len(kept) >= config.max_total:
                _reject(cue, "density_limit",
                        f"the whole-episode ceiling of {config.max_total} "
                        "cue(s) is full")
                continue
            effects += 1
        cue.accepted = True
        kept.append(cue)

    for cue in cues:
        if cue.reject_reason:
            cue.accepted = False


def _too_close(
    cue: AudioCue, kept: Sequence[AudioCue], spacing: float
) -> Optional[AudioCue]:
    """Whether a cue crowds one already kept.

    Beds and silence drops are exempt from spacing against each other and
    against effects: a bed runs *underneath* rather than at a point in time,
    and a silence drop immediately before a hit is the shape the pair is
    supposed to have.
    """
    if cue.kind in ("music_bed", "ambience"):
        return next((other for other in kept
                     if other.kind in ("music_bed", "ambience")), None)
    for other in kept:
        if other.kind in ("music_bed", "ambience"):
            continue
        if cue.kind == "silence_drop" or other.kind == "silence_drop":
            # Only a genuine overlap counts between these two.
            if cue.start < other.end and other.start < cue.end:
                return other
            continue
        if abs(cue.start - other.start) < spacing:
            return other
    return None


