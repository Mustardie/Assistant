"""Minimal music and sound-effect polish.

Five things, placed rarely:

* a **riser** into a moment the episode has been building towards,
* a **hit** on a fail or a reveal, at the frame it lands,
* a **whoosh** on a real transition -- a change of place or of source file,
* an **ambience or music bed** under a stretch, when the style allows one,
* a **silence drop**: everything out for a beat, so the next thing lands.

## The two rules that do the work

**A cue names the moment it is for.** There is no "place one at every cut"
path. A candidate is generated by something the earlier passes recorded -- a
death screen, a payoff beat, an environment change -- and a cue with nothing
behind it is refused as ``no_moment`` rather than placed hopefully.

**A cue may not land on a word.** Hits, risers and whooshes are checked against
the transcript with a guard band either side, because a sting over the middle
of a sentence is the single most obvious way an automated edit announces
itself. Beds are the exception and are ducked instead -- and the plan says so
in the cue's own safety notes rather than in a footnote.

## What it does not do

Nothing here plays a sound. In ``placeholders`` mode no library is read at all
and every cue is a note; in ``assets`` mode the Session 6 matcher is asked, and
anything it cannot satisfy stays a note and lands on the shopping list. Levels
are never measured, loops are never checked for a clean seam, and no cue is
ever executed by this package.
"""
from __future__ import annotations

from typing import Optional, Sequence

from editing.polish.schema import (
    CUE_REQUIREMENT, SFX_KINDS, AudioCue, AudioPolishConfig, AudioPolishPlan,
    allowed_cue_kinds, cue_id_for, now,
)
from editing.roughcut.schema import RoughCutPlan
from editing.schema import StructureTimeline, TimelineSegment
from editing.style.presets import StylePreset

#: Seconds before a moment that a riser starts. Long enough to be a build,
#: short enough that it does not sit under the previous section.
RISER_LEAD = 3.0

#: How long a hit occupies. A one-shot; the number is for the plan's arithmetic
#: rather than a claim about any particular file.
HIT_SECONDS = 1.2

#: How long a whoosh occupies, straddling the cut.
WHOOSH_SECONDS = 0.8

#: How long everything drops out for, before a moment lands.
SILENCE_SECONDS = 0.6

#: Importance levels that can earn a hit.
HIT_IMPORTANCE = frozenset({"payoff", "reveal", "danger"})

#: Importance levels a riser may build into.
RISER_IMPORTANCE = frozenset({"payoff", "reveal"})

#: A clip shorter than this is too short to carry a cue of its own.
MIN_CLIP_SECONDS = 2.0

#: A bed needs a stretch at least this long to be worth laying.
MIN_BED_SECONDS = 20.0


def build_audio_plan(
    timeline: StructureTimeline,
    cut: RoughCutPlan,
    style: StylePreset,
    config: AudioPolishConfig,
    *,
    library=None,
    name: str = "structure",
) -> AudioPolishPlan:
    """Every cue this pass considered, accepted and refused together.

    ``library`` is an optional ``AssetLibrary``. It is read only in ``assets``
    mode; in ``placeholders`` mode it is ignored entirely, so a run with no
    library produces exactly the same plan.
    """
    config = config.validated()
    plan = AudioPolishPlan(
        name=name,
        mode=config.mode,
        config=config,
        style=style.name,
        sequence_name=cut.sequence_name,
        cut_duration=round(cut.total_duration, 3),
        generated_at=now(),
        warnings=list(config.warnings),
    )

    if not config.enabled:
        plan.safety_notes.append(
            "No cue was considered: audio polish is off for this run."
        )
        return plan

    allowed = allowed_cue_kinds(style)
    speech = _speech_spans(timeline, cut)
    candidates = _candidates(timeline, cut, config)

    for cue in candidates:
        if cue.kind not in allowed:
            _reject(cue, "style_forbids",
                    f"the {style.name} style does not use {cue.kind} cues")
            continue
        if cue.kind == "music_bed" and not config.music_bed:
            _reject(cue, "bed_not_allowed",
                    "a music or ambience bed is not allowed for this run")
            continue
        if cue.priority < config.min_priority:
            _reject(cue, "no_moment",
                    f"scored {cue.priority:.2f}, below the "
                    f"{config.min_priority:.2f} a cue needs to be placed")
            continue
        if cue.kind in SFX_KINDS or cue.kind == "silence_drop":
            overlap = _covers_speech(cue, speech, config.speech_guard)
            if overlap is not None:
                _reject(cue, "would_cover_speech",
                        f"a line is being spoken at {overlap:.1f}s and a "
                        f"{cue.kind} there would land on it")
                continue

    _apply_budget(candidates, config, plan)

    if config.uses_library:
        _resolve_assets(candidates, library, plan)
    else:
        for cue in candidates:
            if cue.accepted:
                cue.placeholder_only = True
                cue.safety_notes.append(
                    "placeholder only: no library was read for this run")

    _finish(plan, candidates, config)
    return plan


# ---------------------------------------------------------------------------
# Candidates
# ---------------------------------------------------------------------------

def _candidates(
    timeline: StructureTimeline,
    cut: RoughCutPlan,
    config: AudioPolishConfig,
) -> list[AudioCue]:
    """Everything this pass can argue for, before any rule refuses it."""
    out: list[AudioCue] = []
    moments = _moments(timeline, cut)

    for moment in moments:
        out.extend(_cues_for_moment(moment))

    out.extend(_transition_cues(cut))
    out.extend(_bed_cues(cut, config))

    out.sort(key=lambda cue: (cue.start, cue.kind))
    return out


class _Moment:
    """One thing worth marking, resolved onto the cut."""

    def __init__(self, at: float, segment: TimelineSegment, placement,
                 kind: str, why: str, strength: float):
        self.at = at
        self.segment = segment
        self.placement = placement
        self.kind = kind          # "payoff" / "reveal" / "death" / "danger"
        self.why = why
        self.strength = strength


def _moments(timeline: StructureTimeline, cut: RoughCutPlan) -> list[_Moment]:
    """Where the earlier passes said something lands, in sequence time."""
    from editing.roughcut.select import map_to_sequence

    out: list[_Moment] = []
    for segment in timeline.segments:
        importance = segment.importance
        death = any(getattr(event.ui, "death_screen", False)
                    for event in segment.events)
        reaction = segment.audio_reaction

        if not death and importance not in HIT_IMPORTANCE:
            continue

        # Where the moment actually lands, not where the segment starts. A
        # segment is eight seconds of footage; the scream inside it is the
        # frame a sting belongs on, and marking the segment boundary instead
        # would put every cue up to eight seconds early.
        source_at = segment.start
        if death:
            source_at = min(
                (event.start for event in segment.events
                 if getattr(event.ui, "death_screen", False)),
                default=segment.start)
        elif reaction is not None:
            source_at = reaction.start

        at = map_to_sequence(cut.placements, segment.asset_id, source_at)
        if at is None:
            at = map_to_sequence(
                cut.placements, segment.asset_id, segment.start)
        if at is None:
            continue
        placement = cut.placement_at(at)

        if death:
            out.append(_Moment(
                at, segment, placement, "death",
                "a death screen is on screen here", 0.85))
            continue
        strength = 0.55 + min(0.25, segment.usefulness * 0.25)
        if reaction is not None:
            strength = min(1.0, strength + 0.12)
        out.append(_Moment(
            at, segment, placement, importance,
            f"the picture here is a {importance}"
            + (f" and the audio spikes ({reaction.type})"
               if reaction is not None else ""),
            strength))
    return out


def _cues_for_moment(moment: _Moment) -> list[AudioCue]:
    """The cues one moment could justify. Usually one, sometimes two."""
    out: list[AudioCue] = []
    short_clip = (
        moment.placement is not None
        and moment.placement.sequence_duration < MIN_CLIP_SECONDS
    )

    hit = AudioCue(
        cue_id=cue_id_for("hit", moment.at),
        kind="hit",
        start=round(moment.at, 3),
        end=round(moment.at + HIT_SECONDS, 3),
        target=f"the {moment.kind} at {moment.at:.1f}s",
        moment="death_or_fail" if moment.kind == "death" else (
            "reveal" if moment.kind == "reveal" else (
                "payoff_line" if moment.kind == "payoff" else "danger")),
        placement_id=(moment.placement.placement_id
                      if moment.placement else ""),
        segment_id=moment.segment.segment_id,
        priority=round(moment.strength, 3),
        reason=f"a sting marks the moment: {moment.why}",
        placeholder=("a hard one-shot for a fail" if moment.kind == "death"
                     else "a hard one-shot sting"),
        evidence=[moment.why],
    )
    if short_clip:
        _reject(hit, "clip_too_short",
                f"the clip under this moment is "
                f"{moment.placement.sequence_duration:.1f}s, too short to "
                "carry a sting cleanly")
    out.append(hit)

    if moment.kind in RISER_IMPORTANCE and moment.at >= RISER_LEAD:
        out.append(AudioCue(
            cue_id=cue_id_for("riser", moment.at - RISER_LEAD),
            kind="riser",
            start=round(moment.at - RISER_LEAD, 3),
            end=round(moment.at, 3),
            target=f"the {moment.kind} at {moment.at:.1f}s",
            moment="reveal" if moment.kind == "reveal" else "payoff_line",
            placement_id=(moment.placement.placement_id
                          if moment.placement else ""),
            segment_id=moment.segment.segment_id,
            priority=round(max(0.0, moment.strength - 0.08), 3),
            reason=f"a build into the {moment.kind} three seconds later",
            placeholder="a riser or build, about three seconds",
            evidence=[moment.why],
        ))

    if moment.kind in ("reveal", "death") and moment.at >= SILENCE_SECONDS:
        out.append(AudioCue(
            cue_id=cue_id_for("silence_drop", moment.at - SILENCE_SECONDS),
            kind="silence_drop",
            start=round(moment.at - SILENCE_SECONDS, 3),
            end=round(moment.at, 3),
            target=f"the {moment.kind} at {moment.at:.1f}s",
            moment="reveal" if moment.kind == "reveal" else "death_or_fail",
            placement_id=(moment.placement.placement_id
                          if moment.placement else ""),
            segment_id=moment.segment.segment_id,
            priority=round(max(0.0, moment.strength - 0.15), 3),
            reason="everything out for half a second, so the moment lands",
            placeholder="",
            evidence=[moment.why],
        ))
    return out


def _transition_cues(cut: RoughCutPlan) -> list[AudioCue]:
    """A whoosh only where there is a real transition.

    "Real" means the cut moves to a different source file, which is the one
    boundary this layer can see without guessing: two clips from the same
    recording are a trim, and marking a trim with a whoosh is exactly the spam
    this pass exists not to produce.
    """
    out: list[AudioCue] = []
    previous = None
    for placement in cut.placements:
        if previous is not None and placement.asset_id != previous.asset_id:
            at = placement.sequence_start
            cue = AudioCue(
                cue_id=cue_id_for("whoosh", at),
                kind="whoosh",
                start=round(max(0.0, at - WHOOSH_SECONDS / 2), 3),
                end=round(at + WHOOSH_SECONDS / 2, 3),
                target=f"the change of source at {at:.1f}s",
                placement_id=placement.placement_id,
                priority=0.55,
                reason="the cut moves to a different recording here, which a "
                       "viewer reads as a section change",
                placeholder="a short transition whoosh",
                evidence=[f"clip {previous.placement_id} -> "
                          f"{placement.placement_id}"],
            )
            if placement.sequence_duration < MIN_CLIP_SECONDS:
                _reject(cue, "clip_too_short",
                        f"the clip after this transition is "
                        f"{placement.sequence_duration:.1f}s")
            out.append(cue)
        previous = placement
    return out


def _bed_cues(
    cut: RoughCutPlan, config: AudioPolishConfig
) -> list[AudioCue]:
    """At most one bed, under the whole cut.

    One rather than several on purpose. Deciding where a piece of music should
    start and stop is a creative call this layer has no evidence for, and a
    dozen bed segments would be a dozen guesses. One bed under the episode is a
    single, obvious, easily-refused proposal.
    """
    duration = cut.total_duration
    if duration < MIN_BED_SECONDS:
        return [_bed(0.0, duration, config, refused=(
            "clip_too_short",
            f"the cut is {duration:.0f}s, shorter than the {MIN_BED_SECONDS:.0f}s "
            "a bed needs to be worth laying"))]

    end = min(duration, config.max_bed_seconds)
    cue = _bed(0.0, end, config)
    if end < duration:
        cue.safety_notes.append(
            f"the bed stops at {end:.0f}s of a {duration:.0f}s cut; a longer "
            "one would need a second piece of music rather than a longer loop")
    return [cue]


def _bed(start: float, end: float, config: AudioPolishConfig,
         *, refused: Optional[tuple] = None) -> AudioCue:
    cue = AudioCue(
        cue_id=cue_id_for("music_bed", start),
        kind="music_bed",
        start=round(start, 3),
        end=round(end, 3),
        target="the whole cut",
        priority=0.55,
        reason="a bed under the episode, ducked under the commentary",
        placeholder="a loopable low-intensity bed",
        evidence=[f"{end - start:.0f}s of cut"],
    )
    if config.ducking:
        cue.safety_notes.append(
            "the plan asks for this to duck under speech; the amount is not "
            "measured and has to be set by ear")
    else:
        cue.safety_notes.append(
            "ducking is off, so this sits under the commentary at a fixed "
            "level -- check it by ear before trusting it")
    cue.safety_notes.append(
        "a bed longer than its file is tiled, not crossfaded, so a file that "
        "does not loop cleanly will have an audible seam")
    if refused is not None:
        _reject(cue, refused[0], refused[1])
    return cue


